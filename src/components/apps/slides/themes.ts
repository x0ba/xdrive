export function createSlideFromLayout(
  layout: SlideLayoutKind,
  title = 'New slide',
): SlidePage {
  return {
    id: uid('slide'),
    title,
    layout,
    transition: 'fade',
    transitionMs: 320,
    skipped: false,
    speakerNotes:
      'State the single claim on this slide, then pause for questions.',
    elements: createElementsForLayout(layout, title),
  }
}

