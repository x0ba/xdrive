export function getSlideTheme(themeId: string): SlideThemeSpec {
  return SLIDE_THEMES.find((t) => t.id === themeId) ?? SLIDE_THEMES[0]
}

function uid(prefix: string): string {
  return `${prefix}-${Math.random().toString(36).slice(2, 8)}`
}

